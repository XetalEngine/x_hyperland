"""Ordered, profile-local window preferences with safe wildcard matching."""
import copy
import fnmatch
import hashlib
import json
from pathlib import Path
import re
from effects.window_close import rules as buttons

ROOT = Path(__file__).resolve().parent
PATH = ROOT/'rules.json'
CONFIG = ROOT/'rules.conf'
DEFAULT = dict(id='', name='New rule', enabled=True, app='', title='', layout='inherit', workspace=0,
               monitor='', width=0, height=0, position='inherit', x=0, y=0, fullscreen='inherit',
               opacity=-1, rounding=-1, border=-1, pin='inherit', focus='inherit', controls=None)


def validate(document):
    if not isinstance(document, dict) or set(document) != {'version', 'rules'} or document['version'] != 1:
        raise ValueError('Unsupported window rules file.')
    if not isinstance(document['rules'], list) or len(document['rules']) > 256:
        raise ValueError('Use up to 256 window rules.')
    result = copy.deepcopy(document); identities = set()
    for item in result['rules']:
        if not isinstance(item, dict) or set(item) != set(DEFAULT): raise ValueError('Incomplete window rule.')
        if not re.fullmatch('[a-f0-9]{32}', item['id']) or item['id'] in identities: raise ValueError('Invalid rule identity.')
        identities.add(item['id'])
        for key in ('name', 'app', 'title', 'monitor'):
            value = item[key]
            if not isinstance(value, str) or len(value.encode()) > 256 or any(ord(c) < 32 or c in '#{};,\\' for c in value):
                raise ValueError('Use a short '+key+' without configuration separators.')
        if not item['app'].strip() or not item['name'].strip(): raise ValueError('Enter a rule name and an application ID.')
        # Only * and ? are wildcards, so native and Python readers agree.
        if any(c in item['app']+item['title'] for c in '[]'): raise ValueError('Use * or ? for wildcard matches.')
        if type(item['enabled']) is not bool: raise ValueError('Invalid enabled flag.')
        for key, choices in [('layout', ('inherit','tile','floating')), ('position', ('inherit','center','custom')),
                             ('fullscreen', ('inherit','normal','maximized','fullscreen')), ('pin', ('inherit','on','off')),
                             ('focus', ('inherit','on','off'))]:
            if item[key] not in choices: raise ValueError('Invalid '+key+'.')
        for key, lo, hi in [('workspace',0,100),('width',0,32768),('height',0,32768),('x',-32768,32768),
                            ('y',-32768,32768),('opacity',-1,100),('rounding',-1,100),('border',-1,20)]:
            if type(item[key]) is not int or not lo <= item[key] <= hi: raise ValueError('Invalid '+key+'.')
        if bool(item['width']) != bool(item['height']): raise ValueError('Set both width and height, or leave both automatic.')
        if item['controls'] is not None: item['controls'] = buttons.validate(item['controls'])
    return result


def load(path=PATH):
    raw = path.read_bytes() if path.exists() else b''
    if len(raw) > 1024*1024: raise ValueError('Window rules file is too large.')
    return validate(json.loads(raw) if raw else {'version':1, 'rules':[]}), hashlib.sha256(raw).hexdigest()


def matches(rule, app, title=''):
    return rule['enabled'] and fnmatch.fnmatchcase(app, rule['app']) and (not rule['title'] or fnmatch.fnmatchcase(title, rule['title']))


def expression(pattern):
    return '^('+''.join('.*' if c == '*' else '.' if c == '?' else re.escape(c) for c in pattern)+')$'


def render(document):
    lines = ['# Generated by Fusion Settings / Window Rules. Workspace overrides remain authoritative.']
    for item in validate(document)['rules']:
        if not item['enabled']: continue
        lines += ['windowrule {', '    name = fusion-user-'+item['id'], '    match:initial_class = '+expression(item['app'])]
        if item['title']: lines += ['    match:initial_title = '+expression(item['title'])]
        effects = []
        if item['layout'] != 'inherit': effects += ['float = '+('on' if item['layout']=='floating' else 'off')]
        if item['workspace']: effects += [f"workspace = {item['workspace']} silent"]
        if item['monitor']: effects += ['monitor = '+item['monitor']]
        if item['width']: effects += [f"size = {item['width']} {item['height']}"]
        if item['position'] == 'center': effects += ['center = on']
        if item['position'] == 'custom': effects += [f"move = {item['x']} {item['y']}"]
        if item['fullscreen'] != 'inherit':
            mode={'normal':0,'maximized':1,'fullscreen':2}[item['fullscreen']]
            effects += [f'fullscreen_state = {mode} {mode}']
        if item['pin'] != 'inherit': effects += ['pin = '+item['pin']]
        if item['focus'] != 'inherit': effects += ['no_initial_focus = '+('on' if item['focus']=='off' else 'off')]
        if effects: effects += ['tag = +fusion-managed-rule']
        if item['opacity'] >= 0: effects += [f"opacity = {item['opacity']/100:.2f} override"]
        if item['rounding'] >= 0: effects += [f"rounding = {item['rounding']}"]
        if item['border'] >= 0: effects += [f"border_size = {item['border']}"]
        if not effects:
            del lines[-(3 + bool(item['title'])):]
            continue
        lines += ['    '+effect for effect in effects] + ['}']
    return '\n'.join(lines)+'\n'


def launch_managed(classes):
    normalize = lambda value: re.sub('[^a-z0-9*?]', '', value.casefold())
    try:
        document, _ = load()
        return any(r['enabled'] and any(fnmatch.fnmatchcase(normalize(c), normalize(r['app'])) for c in classes)
                   and (r['layout'] != 'inherit' or r['width'] or r['position'] != 'inherit' or r['fullscreen'] != 'inherit')
                   for r in document['rules'])
    except (OSError, ValueError): return False
